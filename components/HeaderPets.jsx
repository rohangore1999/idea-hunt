// ─── Pet component ─────────────────────────────────────────────────────────
function Pet({ pet, containerWidth }) {
  const [x, setX]         = useState(() => Math.random() * (containerWidth - 28))
  const [dir, setDir]     = useState(() => (Math.random() > 0.5 ? 1 : -1))
  const [frame, setFrame] = useState(0)

  const xRef        = useRef(x)
  const dirRef      = useRef(dir)
  const animRef     = useRef(null)
  const lastTimeRef = useRef(null)
  const frameTimer  = useRef(0)

  useEffect(() => {
    if (!containerWidth) return
    const frameDuration = 1 / pet.fps

    const tick = (ts) => {
      if (!lastTimeRef.current) lastTimeRef.current = ts
      const dt = Math.min((ts - lastTimeRef.current) / 1000, 0.05)
      lastTimeRef.current = ts

      xRef.current += dirRef.current * pet.speed * dt
      if (xRef.current > containerWidth - 28) {
        xRef.current = containerWidth - 28
        dirRef.current = -1; setDir(-1)
      } else if (xRef.current < 0) {
        xRef.current = 0
        dirRef.current = 1; setDir(1)
      }

      frameTimer.current += dt
      if (frameTimer.current >= frameDuration) {
        frameTimer.current -= frameDuration
        setFrame(f => (f + 1) % pet.frames.length)
      }

      setX(xRef.current)
      animRef.current = requestAnimationFrame(tick)
    }

    animRef.current = requestAnimationFrame(tick)
    return () => cancelAnimationFrame(animRef.current)
  }, [containerWidth, pet])

  return (
    <div
      className="absolute pointer-events-none"
      style={{ left: x, bottom: 0, willChange: 'transform' }}
    >
      {pet.frames[frame](dir === -1)}
    </div>
  )
}

// ─── Container ─────────────────────────────────────────────────────────────
export default function HeaderPets() {
  const ref = useRef(null)
  const [width, setWidth] = useState(0)

  useEffect(() => {
    if (!ref.current) return
    setWidth(ref.current.offsetWidth)
    const ro = new ResizeObserver(([e]) => setWidth(e.contentRect.width))
    ro.observe(ref.current)
    return () => ro.disconnect()
  }, [])

  return (
    <div ref={ref} className="absolute inset-0 overflow-hidden pointer-events-none z-10">
      {width > 0 && PETS.map((pet) => (
        <Pet key={pet.id} pet={pet} containerWidth={width} />
      ))}
    </div>
  )
}
